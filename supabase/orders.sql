-- ------------------------------------------------------------
-- 2. Tablas de pedidos
-- ------------------------------------------------------------

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  code text unique not null,
  customer_name text not null,
  customer_phone text not null,
  customer_email text default '',
  customer_address text not null,
  customer_city text not null,
  payment_method text not null default '',
  payment_status text not null default 'pendiente'
    check (payment_status in ('pendiente', 'comprobante_enviado', 'pagado', 'contra_entrega', 'reembolsado')),
  payment_proof_path text default '',
  payment_reference text default '',
  notes text default '',
  subtotal numeric(10,2) not null default 0,
  shipping numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  status text not null default 'pendiente'
    check (status in ('pendiente', 'confirmado', 'pedido_proveedor', 'en_camino', 'entregado', 'cancelado')),
  tracking_code text default '',
  preorder_accepted boolean not null default false,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  size text default '',
  qty int not null default 1,
  unit_price numeric(10,2) not null default 0,
  line_total numeric(10,2) not null default 0
);

create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  status text not null default '',
  note text default '',
  created_at timestamptz default now()
);

create index if not exists orders_status_idx on public.orders(status);
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_code_idx on public.orders(code);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists order_events_order_idx on public.order_events(order_id);

